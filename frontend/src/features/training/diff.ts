export type DiffType = 'eq' | 'add' | 'del'

export interface DiffLine {
  type: DiffType
  text: string
}

/**
 * Line-level diff of two texts via a longest-common-subsequence backtrace.
 * Returns the merged sequence: shared lines as `eq`, lines only in `before` as
 * `del`, lines only in `after` as `add`. Hand-rolled to avoid a dependency
 * (CLAUDE.md: prefer stdlib / ask before deps); the inputs here are small
 * pretty-printed JSON blobs, so the O(n·m) table is fine.
 */
export function diffLines(before: string, after: string): DiffLine[] {
  const a = before.split('\n')
  const b = after.split('\n')
  const n = a.length
  const m = b.length

  // lcs[i][j] = length of the LCS of a[i:] and b[j:].
  const lcs: number[][] = Array.from({ length: n + 1 }, () =>
    new Array<number>(m + 1).fill(0),
  )
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      lcs[i][j] =
        a[i] === b[j]
          ? lcs[i + 1][j + 1] + 1
          : Math.max(lcs[i + 1][j], lcs[i][j + 1])
    }
  }

  // Walk the table forward, emitting deletions/additions before shared lines.
  const out: DiffLine[] = []
  let i = 0
  let j = 0
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      out.push({ type: 'eq', text: a[i] })
      i++
      j++
    } else if (lcs[i + 1][j] >= lcs[i][j + 1]) {
      out.push({ type: 'del', text: a[i] })
      i++
    } else {
      out.push({ type: 'add', text: b[j] })
      j++
    }
  }
  while (i < n) out.push({ type: 'del', text: a[i++] })
  while (j < m) out.push({ type: 'add', text: b[j++] })
  return out
}
